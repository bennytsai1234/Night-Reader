/// 一件背景工作走到哪（ADR 0058；階段表在 `docs/state-machines.md`
/// 「背景工作的生命週期」）。互斥：一件工作同時只在其中一個。
///
/// 工作本身（找書、修復、整批、校驗、搜尋）記它自己用到的幾個；頁面那層
/// （`RepairRun`）另記工作不知道的（未開始、讀回中），算出頁面與通知讀的
/// 那一個。
enum WorkPhase {
  /// 還沒開始：頁面剛推入、推入動畫還沒播完。
  ready,

  /// 做著：通知放「暫停」「結束」。
  running,

  /// 按了暫停、還沒停好：通知與頁面寫「正在暫停…」，還能按結束（結束蓋過
  /// 暫停）。
  pausing,

  /// 按了結束、還沒停好：通知與頁面寫「正在結束…」。
  ending,

  /// 停在做完的那一步，位置空出來，等使用者按繼續或結束。
  paused,

  /// 暫停中按了繼續、正在讀回存檔：頁面照舊是已暫停，「繼續」灰掉。
  resuming,

  /// 等使用者：剪貼簿的 AI 修復等貼回（不是背景工作，沒有通知）。
  waiting,

  /// 做完（含結束、出錯）。
  finished;

  /// 正在暫停或結束、還沒停好：通知不放按鈕。
  bool get settling => this == pausing || this == ending;

  /// 做著（含正在暫停、正在結束）：佔著背景工作的位置。
  bool get active => this == running || settling;
}
